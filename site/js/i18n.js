const DICTS = { nl, en };

let lang = 'nl';
try { lang = localStorage.getItem('prompt.lang') || (navigator.language?.startsWith('nl') ? 'nl' : 'en'); } catch { /* storage blocked */ }
if (!DICTS[lang]) lang = 'nl';

export function getLang() { return lang; }
export function setLang(next) {
  lang = DICTS[next] ? next : 'nl';
  try { localStorage.setItem('prompt.lang', lang); } catch { /* storage blocked */ }
  document.documentElement.lang = lang;
}
export function t(key, params = {}) {
  const s = DICTS[lang][key] ?? DICTS.nl[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
}
